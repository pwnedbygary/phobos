# ---- Text and numbers ------------------------------------------------------------------------------------------------


def esc(text):
    """Text for SVG and HTML: the five characters XML gives meaning to, escaped."""
    return (
        str(text)
        .replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
        .replace('"', "&quot;")
        .replace("'", "&#39;")
    )


def coord(value):
    """A coordinate with at most one decimal, without a trailing .0, so output never depends on float noise."""
    text = f"{value:.1f}"
    if text.endswith(".0"):
        text = text[:-2]
    return "0" if text == "-0" else text


def value_text(value, decimals):
    if decimals == "auto":
        text = f"{value:,.2f}".rstrip("0").rstrip(".")
        return text
    return f"{value:,.{decimals}f}"


def chart_decimals(chart):
    if "decimals" in chart:
        return chart["decimals"]
    values = [v for s in chart["series"] for v in s["values"]]
    return 0 if all(float(v).is_integer() for v in values) else 1


def text_width(text, size):
    """Width of text in the system sans-serif fonts, estimated from character classes (generous, never short)."""
    units = 0.0
    for ch in text:
        if ch in "ijl.,:;'|!":
            units += 0.30
        elif ch in " ()[]-/":
            units += 0.36
        elif ch in "mwMW@%":
            units += 0.88
        elif ch.isupper() or ch in "#&":
            units += 0.68
        elif ch.isdigit():
            units += 0.58
        else:
            units += 0.56
    return units * size


def wrap(text, size, width):
    lines, line = [], ""
    for word in text.split():
        candidate = f"{line} {word}" if line else word
        if line and text_width(candidate, size) > width:
            lines.append(line)
            line = word
        else:
            line = candidate
    if line:
        lines.append(line)
    return lines


def nice_step(span, target=5):
    """The round step (1, 2, 2.5 or 5 times a power of ten) giving the nearest to `target` intervals over `span`."""
    if span <= 0:
        return 1
    magnitude = 10 ** math.floor(math.log10(span / target))
    best = None
    for multiple in (1, 2, 2.5, 5, 10):
        step = multiple * magnitude
        score = abs(span / step - target)
        if best is None or score < best[0] - 1e-9:
            best = (score, step)
    return best[1]


def value_scale(maximum, fixed):
    """The value axis: its top, its ticks and their decimals. A fixed top (a chart's value_max) is kept as is."""
    step = nice_step(fixed if fixed else maximum)
    top = fixed if fixed else math.ceil(maximum / step - 1e-9) * step
    ticks = []
    k = 0
    while k * step <= top + 1e-9:
        ticks.append(round(k * step, 6))
        k += 1
    digits = f"{step:.6f}".rstrip("0").rstrip(".")
    decimals = len(digits.split(".")[1]) if "." in digits else 0
    return top, ticks, decimals


# ---- SVG pieces --------------------------------------------------------------------------------------------------


def text_el(x, y, content, size=12, fill=None, anchor="start", weight=None, halo=None):
    """A text element; `halo` (the background color) outlines it so a gridline or reference line behind stays clear."""
    attrs = [f'x="{coord(x)}"', f'y="{coord(y)}"', f'font-size="{coord(size)}"']
    if fill:
        attrs.append(f'fill="{fill}"')
    if anchor != "start":
        attrs.append(f'text-anchor="{anchor}"')
    if weight:
        attrs.append(f'font-weight="{weight}"')
    if halo:
        attrs.append(f'stroke="{halo}" stroke-width="3" stroke-linejoin="round" paint-order="stroke"')
    return f"<text {' '.join(attrs)}>{esc(content)}</text>"


def rect_el(x, y, w, h, fill, rx=0):
    corner = f' rx="{coord(rx)}"' if rx else ""
    return (
        f'<rect x="{coord(x)}" y="{coord(y)}" width="{coord(max(w, 0))}" height="{coord(max(h, 0))}"'
        f'{corner} fill="{fill}"/>'
    )


def line_el(x1, y1, x2, y2, stroke, width=1, dash=None):
    dashed = f' stroke-dasharray="{dash}"' if dash else ""
    return (
        f'<line x1="{coord(x1)}" y1="{coord(y1)}" x2="{coord(x2)}" y2="{coord(y2)}" '
        f'stroke="{stroke}" stroke-width="{coord(width)}"{dashed}/>'
    )


class Frame:
    """The parts every chart shares: background, title, legend, caption, and the space left for the plot."""

    def __init__(self, chart, theme):
        self.chart = chart
        self.theme = theme
        self.width = chart.get("width", WIDTH)
        self.height = chart.get("height", HEIGHT)
        self.parts = []
        self.legend_bottom = 0
        self.caption_top = 0

    def color(self, series):
        return self.theme["tones"][series["tone"]]

    def open(self):
        t, w, h = self.theme, self.width, self.height
        self.parts.append(
            f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" viewBox="0 0 {w} {h}" '
            f'role="img" aria-labelledby="title desc" font-family="{FONT}">'
        )
        self.parts.append(f'<title id="title">{esc(self.chart["title"])}</title>')
        self.parts.append(f'<desc id="desc">{esc(self.chart["alt"])}</desc>')
        self.parts.append(
            f'<rect x="0.5" y="0.5" width="{w - 1}" height="{h - 1}" rx="8" fill="{t["background"]}" '
            f'stroke="{t["border"]}"/>'
        )
        self.parts.append(text_el(20, 30, self.chart["title"], 15, t["text"], weight="600"))

    def legend(self):
        """Series names in a row (wrapped if needed) under the title; returns the baseline of its last row."""
        series = self.chart["series"]
        y = 54
        if len(series) < 2:
            self.legend_bottom = 34
            return
        x = 20
        for s in series:
            item = 14 + text_width(s["name"], 12) + 22
            if x > 20 and x + item > self.width - 20:
                x = 20
                y += 18
            self.parts.append(rect_el(x, y - 9, 10, 10, self.color(s), rx=2))
            self.parts.append(text_el(x + 14, y, s["name"], 12, self.theme["text"]))
            x += item
        self.legend_bottom = y

    def caption(self):
        lines = wrap(self.chart["source"], 11, self.width - 40)
        first = self.height - 14 - 14 * (len(lines) - 1)
        for i, line in enumerate(lines):
            self.parts.append(text_el(20, first + 14 * i, line, 11, self.theme["muted"]))
        self.caption_top = first - 11

    def close(self):
        self.parts.append("</svg>")
        return "\n".join(self.parts) + "\n"


def rotated_label(x, y, content, theme):
    return (
        f'<text x="0" y="0" font-size="12" fill="{theme["muted"]}" text-anchor="middle" '
        f'transform="translate({coord(x)} {coord(y)}) rotate(-90)">{esc(content)}</text>'
    )


