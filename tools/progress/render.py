def vertical_chart(chart, theme_name):
    """Vertical bars (stacked or side by side) and lines: categories along the bottom, values up the left."""
    theme = THEMES[theme_name]
    frame = Frame(chart, theme)
    frame.open()
    frame.legend()
    frame.caption()
    series = chart["series"]
    categories = chart["categories"]
    count = len(categories)
    stacked = chart.get("stacked", False)
    is_line = chart["kind"] == "line"
    show_values = chart.get("show_values", False)
    decimals = chart_decimals(chart)
    references = chart.get("references", [])

    if stacked:
        maximum = max(sum(s["values"][i] for s in series) for i in range(count))
    else:
        maximum = max(v for s in series for v in s["values"])
    maximum = max([maximum] + [r["value"] for r in references])
    if (show_values or chart.get("show_totals")) and "value_max" not in chart:
        maximum *= 1.08
    top_value, ticks, tick_decimals = value_scale(maximum, chart.get("value_max"))

    tick_labels = [value_text(t, tick_decimals) for t in ticks]
    plot_left = 34 + max(text_width(label, 11) for label in tick_labels) + 10
    plot_right = frame.width - 24
    plot_w = plot_right - plot_left
    band = plot_w / count
    category_lines = [wrap(c, 11, band - 6) if text_width(c, 11) > band - 6 else [c] for c in categories]
    extra_lines = max(len(lines) for lines in category_lines) - 1

    axis_label_y = frame.caption_top - 12
    groups = chart.get("category_groups", [])
    group_y = axis_label_y - 18 if groups else None
    tick_y = (group_y if groups else axis_label_y) - 17 - 13 * extra_lines
    plot_top = frame.legend_bottom + 22
    plot_bottom = tick_y - 14
    plot_h = plot_bottom - plot_top

    def y_of(value):
        return plot_bottom - plot_h * (value / top_value)

    parts = frame.parts
    for tick, label in zip(ticks, tick_labels):
        y = y_of(tick)
        parts.append(line_el(plot_left, y, plot_right, y, theme["axis"] if tick == 0 else theme["grid"]))
        parts.append(text_el(plot_left - 8, y + 4, label, 11, theme["muted"], anchor="end"))
    parts.append(rotated_label(20, (plot_top + plot_bottom) / 2, chart["value_label"], theme))

    halo = theme["background"]
    for ref in references:
        y = y_of(ref["value"])
        parts.append(line_el(plot_left, y, plot_right, y, theme["muted"], 1.2, "5 4"))

    labels = []
    centers = [plot_left + band * (i + 0.5) for i in range(count)]
    if is_line:
        for s in series:
            color = frame.color(s)
            points = [(centers[i], y_of(v)) for i, v in enumerate(s["values"])]
            if len(series) == 1:
                area = [(points[0][0], plot_bottom)] + points + [(points[-1][0], plot_bottom)]
                parts.append(
                    f'<polygon points="{" ".join(f"{coord(x)},{coord(y)}" for x, y in area)}" '
                    f'fill="{color}" fill-opacity="0.12"/>'
                )
            parts.append(
                f'<polyline points="{" ".join(f"{coord(x)},{coord(y)}" for x, y in points)}" fill="none" '
                f'stroke="{color}" stroke-width="2.5" stroke-linejoin="round" stroke-linecap="round"/>'
            )
            for (x, y), v in zip(points, s["values"]):
                parts.append(
                    f'<circle cx="{coord(x)}" cy="{coord(y)}" r="3.5" fill="{color}" '
                    f'stroke="{theme["background"]}" stroke-width="1.5"/>'
                )
                if show_values:
                    labels.append(text_el(x, y - 9, value_text(v, decimals), 10.5, theme["text"], anchor="middle",
                                          halo=halo))
    elif stacked:
        bar_w = min(band * 0.68, 56)
        for i in range(count):
            x = centers[i] - bar_w / 2
            total = 0
            for s in series:
                v = s["values"][i]
                if v > 0:
                    parts.append(rect_el(x, y_of(total + v), bar_w, y_of(total) - y_of(total + v), frame.color(s)))
                total += v
            if chart.get("show_totals"):
                labels.append(text_el(centers[i], y_of(total) - 6, value_text(total, decimals), 10.5,
                                      theme["text"], anchor="middle", halo=halo))
    else:
        group_w = min(band * 0.76, 66 * len(series))
        bar_w = group_w / len(series)
        for i in range(count):
            for j, s in enumerate(series):
                v = s["values"][i]
                x = centers[i] - group_w / 2 + j * bar_w
                parts.append(rect_el(x + 1.5, y_of(v), bar_w - 3, plot_bottom - y_of(v), frame.color(s)))
                if show_values:
                    labels.append(text_el(x + bar_w / 2, y_of(v) - 6, value_text(v, decimals), 10.5,
                                          theme["text"], anchor="middle", halo=halo))
    parts.extend(labels)

    for ref in references:
        y = y_of(ref["value"])
        if ref.get("label_at", "end") == "start":
            parts.append(text_el(plot_left + 6, y - 5, ref["label"], 10.5, theme["muted"], halo=halo))
        else:
            parts.append(text_el(plot_right - 4, y - 5, ref["label"], 10.5, theme["muted"], anchor="end", halo=halo))

    for i, lines in enumerate(category_lines):
        for k, line in enumerate(lines):
            parts.append(text_el(centers[i], tick_y + 13 * k, line, 11, theme["text"], anchor="middle"))
    for g in groups:
        start = plot_left + band * g["first"]
        end = plot_left + band * (g["last"] + 1)
        parts.append(text_el((start + end) / 2, group_y, g["label"], 11, theme["muted"], anchor="middle"))
        if g["first"] > 0:
            parts.append(line_el(start, plot_bottom + 2, start, group_y + 2, theme["axis"]))
    parts.append(text_el((plot_left + plot_right) / 2, axis_label_y, chart["category_label"], 12, theme["muted"],
                         anchor="middle"))
    return frame.close()


def horizontal_chart(chart, theme_name):
    """Horizontal bars, side by side within each category: categories down the left, values along the bottom."""
    theme = THEMES[theme_name]
    frame = Frame(chart, theme)
    frame.open()
    frame.legend()
    frame.caption()
    series = chart["series"]
    categories = chart["categories"]
    count = len(categories)
    show_values = chart.get("show_values", False)
    decimals = chart_decimals(chart)
    references = chart.get("references", [])

    maximum = max([v for s in series for v in s["values"]] + [r["value"] for r in references])
    top_value, ticks, tick_decimals = value_scale(maximum, chart.get("value_max"))

    axis_label_y = frame.caption_top - 12
    tick_y = axis_label_y - 18
    plot_top = frame.legend_bottom + (30 if references else 22)
    plot_bottom = tick_y - 14
    label_lines = [wrap(c, 12, 260) for c in categories]
    plot_left = 36 + max(text_width(line, 12) for lines in label_lines for line in lines) + 12
    value_room = 0
    if show_values:
        value_room = max(text_width(value_text(v, decimals), 10.5) for s in series for v in s["values"])
    plot_right = frame.width - 20 - value_room - (8 if show_values else 0)
    plot_w = plot_right - plot_left
    plot_h = plot_bottom - plot_top

    def x_of(value):
        return plot_left + plot_w * (value / top_value)

    parts = frame.parts
    for tick in ticks:
        x = x_of(tick)
        parts.append(line_el(x, plot_top, x, plot_bottom, theme["axis"] if tick == 0 else theme["grid"]))
        parts.append(text_el(x, tick_y, value_text(tick, tick_decimals), 11, theme["muted"], anchor="middle"))

    halo = theme["background"]
    for ref in references:
        x = x_of(ref["value"])
        parts.append(line_el(x, plot_top - 4, x, plot_bottom, theme["muted"], 1.2, "5 4"))
        parts.append(text_el(x, plot_top - 9, ref["label"], 10.5, theme["muted"], anchor="middle", halo=halo))

    band = plot_h / count
    group_h = min(band * 0.76, 22 * len(series))
    bar_h = group_h / len(series)
    labels = []
    for i in range(count):
        center = plot_top + band * (i + 0.5)
        lines = label_lines[i]
        first = center + 4 - 7 * (len(lines) - 1)
        for k, line in enumerate(lines):
            parts.append(text_el(plot_left - 8, first + 14 * k, line, 12, theme["text"], anchor="end"))
        for j, s in enumerate(series):
            v = s["values"][i]
            y = center - group_h / 2 + j * bar_h
            parts.append(rect_el(plot_left, y + 1, x_of(v) - plot_left, bar_h - 2, frame.color(s), rx=1.5))
            if show_values:
                labels.append(text_el(x_of(v) + 5, y + bar_h / 2 + 3.6, value_text(v, decimals), 10.5,
                                      theme["text"], halo=halo))
    parts.extend(labels)

    parts.append(rotated_label(20, (plot_top + plot_bottom) / 2, chart["category_label"], theme))
    parts.append(text_el((plot_left + plot_right) / 2, axis_label_y, chart["value_label"], 12, theme["muted"],
                         anchor="middle"))
    return frame.close()


def chart_svg(chart, theme_name):
    if chart["kind"] == "bar" and chart.get("orientation") == "horizontal":
        return horizontal_chart(chart, theme_name)
    return vertical_chart(chart, theme_name)


# ---- Markdown ---------------------------------------------------------------------------------------------------


def cell(text):
    return str(text).replace("|", "\\|")


def picture(chart, prefix):
    return "\n".join([
        "<picture>",
        f'  <source media="(prefers-color-scheme: dark)" srcset="{prefix}{chart["id"]}-dark.svg">',
        f'  <img alt="{esc(chart["alt"])}" src="{prefix}{chart["id"]}-light.svg" width="880">',
        "</picture>",
    ])


def mermaid_init():
    """A theme for Mermaid's timeline that reads the same on GitHub's light and dark pages.

    The timeline fills each period's boxes with cScale0-11 and writes on them in cScaleLabel0-11; its axis takes the
    last cScaleLabel and the stems under each period cScaleInv. GitHub's default light theme puts white text on pale
    boxes, so: dark fills with white text, and mid-gray lines, which show on white and on near-black alike. A 10-pixel
    left margin (150 by default) and 20-pixel text keep the words large once GitHub fits the diagram to its column.
    """
    variables = {}
    for i in range(12):
        variables[f"cScale{i}"] = TIMELINE_FILLS[i % len(TIMELINE_FILLS)]
        variables[f"cScaleLabel{i}"] = "#ffffff" if i < len(TIMELINE_FILLS) else TIMELINE_LINE
        variables[f"cScaleInv{i}"] = TIMELINE_LINE
    variables["fontSize"] = "20px"
    config = {"theme": "base", "themeVariables": variables, "timeline": {"leftMargin": 10}}
    return "%%{init: " + json.dumps(config) + "}%%"


def mermaid_timeline(entries):
    lines = ["```mermaid", mermaid_init(), "timeline"]
    for entry in entries:
        lines.append(f"    {entry['period']} : " + " : ".join(entry["events"]))
    lines.append("```")
    return lines


def releases_table(releases):
    rows = ["| Release | Date | Pull requests | Highlights |", "|---|---|---|---|"]
    for r in releases:
        rows.append(f"| {cell(r['tag'])} | {cell(r['date'])} | {cell(r['prs'])} | {cell(r['highlights'])} |")
    return rows


def headline_list(data):
    return [f"- **{h['value']}** {h['label']}" for h in data["headline"]]


def readme_section(data, charts):
    by_tag = {r["tag"]: r for r in data["releases"]}
    out = [GENERATED, "", f"{data['readme_intro']} As of {data['as_of']}:", ""]
    out += headline_list(data)
    out.append("")
    for chart_id in data["readme_charts"]:
        out += [picture(charts[chart_id], "docs/images/progress/"), ""]
    out += mermaid_timeline(data["readme_timeline"])
    out.append("")
    out += releases_table([by_tag[tag] for tag in data["readme_releases"]])
    out += ["", data["nightlies"], ""]
    out.append(
        "The whole story, era by era, with every chart, the firsts, and the setbacks and what changed after them: "
        "[docs/progress.md](docs/progress.md)."
    )
    return "\n".join(out) + "\n"


def readme_text(data, charts):
    text = README.read_text(encoding="utf-8")
    if text.count(BEGIN) != 1 or text.count(END) != 1 or text.index(BEGIN) > text.index(END):
        raise SystemExit(f"progress: {README.name} needs one {BEGIN} and, after it, one {END}")
    before, rest = text.split(BEGIN, 1)
    _, after = rest.split(END, 1)
    return before + BEGIN + "\n" + readme_section(data, charts) + END + after


def page_text(data, charts):
    out = ["# Development progress", "", GENERATED, ""]
    out += [f"{data['intro']} As of {data['as_of']}.", ""]
    out += headline_list(data)
    out += ["", "## Timeline", ""]
    periods = [era["timeline"] for era in data["eras"]]
    for start in range(0, len(periods), TIMELINE_PERIODS):
        out += mermaid_timeline(periods[start:start + TIMELINE_PERIODS]) + [""]
    out += ["## Firsts", "", "| Date | First |", "|---|---|"]
    out += [f"| {cell(f['date'])} | {cell(f['what'])} |" for f in data["firsts"]]
    out += ["", "## The eras", ""]
    for number, era in enumerate(data["eras"], 1):
        out += [f"### {number}. {era['name']} ({era['span']})", "", era["summary"], "", "| Date | Milestone |",
                "|---|---|"]
        for m in era["milestones"]:
            kind = KIND_LABELS[m["kind"]]
            marker = f" ({kind})" if kind else ""
            out.append(f"| {cell(m['date'])} | **{cell(m['title'])}**{marker} — {cell(m['detail'])} |")
        out.append("")
    out += ["## Progress, measured", ""]
    for section in data["chart_sections"]:
        out += [f"### {section['title']}", ""]
        for chart_id in section["charts"]:
            out += [picture(charts[chart_id], "images/progress/"), ""]
    out += ["## Releases", ""]
    out += releases_table(data["releases"])
    out += ["", data["nightlies"], "", "## Setbacks and lessons", "",
            "| When | What happened | What changed after |", "|---|---|---|"]
    out += [f"| {cell(s['when'])} | {cell(s['what'])} | {cell(s['after'])} |" for s in data["setbacks"]]
    out += ["", "## Sources", "", data["sources"], "",
            "This page, the charts and README.md's Development progress section are generated: edit "
            "docs/progress/data.json, then run `python3 tools/progress/render.py`. With `--check` it writes nothing "
            "and fails if any of them no longer matches the data."]
    return "\n".join(out) + "\n"


# ---- Checks on the data -----------------------------------------------------------------------------------------


def validate(data):
    charts = {}
    for chart in data["charts"]:
        if chart["id"] in charts:
            raise SystemExit(f"progress: chart {chart['id']} appears twice")
        charts[chart["id"]] = chart
        for s in chart["series"]:
            if len(s["values"]) != len(chart["categories"]):
                raise SystemExit(f"progress: {chart['id']}: {s['name']} has {len(s['values'])} values for "
                                 f"{len(chart['categories'])} categories")
            if s["tone"] not in THEMES["light"]["tones"]:
                raise SystemExit(f"progress: {chart['id']}: unknown tone {s['tone']}")
    placed = [c for section in data["chart_sections"] for c in section["charts"]]
    for chart_id in placed + data["readme_charts"]:
        if chart_id not in charts:
            raise SystemExit(f"progress: no chart called {chart_id}")
    for chart_id in charts:
        if chart_id not in placed:
            raise SystemExit(f"progress: chart {chart_id} isn't in any chart section")
    tags = {r["tag"] for r in data["releases"]}
    for tag in data["readme_releases"]:
        if tag not in tags:
            raise SystemExit(f"progress: no release {tag}")
    # Mermaid's timeline splits on colons; '#' and ';' start its entity codes.
    timeline = [era["timeline"] for era in data["eras"]] + data["readme_timeline"]
    for entry in timeline:
        for text in [entry["period"]] + entry["events"]:
            if any(ch in text for ch in ":#;"):
                raise SystemExit(f"progress: the timeline can't show {text!r} (no ':', '#' or ';')")
    if len(data["readme_timeline"]) > TIMELINE_PERIODS:
        raise SystemExit(f"progress: README's timeline has more than {TIMELINE_PERIODS} periods")
    for era in data["eras"]:
        for m in era["milestones"]:
            if m["kind"] not in KIND_LABELS:
                raise SystemExit(f"progress: unknown milestone kind {m['kind']}")
    return charts


PLACEHOLDER = re.compile(r"\{([a-z0-9-]+):([^{}:]+)(?::([^{}:]+))?\}")


def chart_number(charts, match):
    """A number from a chart, for {chart:value_max}, {chart:count} or {chart:series:selector}.

    The selector is first, last, min, max or an index; the series "total" sums all series at each category.
    """
    chart_id, name, selector = match.groups()
    chart = charts.get(chart_id)
    if chart is None:
        raise SystemExit(f"progress: {match.group(0)}: no chart called {chart_id}")
    if selector is None:
        if name == "count":
            return str(len(chart["categories"]))
        if name == "value_max" and "value_max" in chart:
            top = chart["value_max"]
            return value_text(top, 0 if float(top).is_integer() else chart_decimals(chart))
        raise SystemExit(f"progress: {match.group(0)}: use count, value_max or series:selector")
    if name == "total":
        values = [sum(s["values"][i] for s in chart["series"]) for i in range(len(chart["categories"]))]
    else:
        found = [s["values"] for s in chart["series"] if s["name"] == name]
        if not found:
            raise SystemExit(f"progress: {match.group(0)}: {chart_id} has no series called {name!r}")
        values = found[0]
    picks = {"first": lambda v: v[0], "last": lambda v: v[-1], "min": min, "max": max}
    if selector in picks:
        return value_text(picks[selector](values), chart_decimals(chart))
    try:
        return value_text(values[int(selector)], chart_decimals(chart))
    except (ValueError, IndexError):
        raise SystemExit(f"progress: {match.group(0)}: no value {selector!r} in {name!r}") from None


def resolve(node, charts):
    """Every {chart:...} in the data's text replaced by the number it names, so text can't drift from the charts."""
    if isinstance(node, dict):
        return {key: resolve(value, charts) for key, value in node.items()}
    if isinstance(node, list):
        return [resolve(value, charts) for value in node]
    if isinstance(node, str):
        text = PLACEHOLDER.sub(lambda match: chart_number(charts, match), node)
        if "{" in text or "}" in text:
            raise SystemExit(f"progress: a placeholder in {node!r} names nothing")
        return text
    return node


def outputs(data):
    data = resolve(data, {chart["id"]: chart for chart in data["charts"]})
    charts = validate(data)
    files = {}
    for chart in data["charts"]:
        for theme in ("light", "dark"):
            files[IMAGES / f"{chart['id']}-{theme}.svg"] = chart_svg(chart, theme)
    files[PAGE] = page_text(data, charts)
    files[README] = readme_text(data, charts)
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true",
                        help="write nothing; exit 1 if a generated file differs from what the data gives")
    args = parser.parse_args()

    data = json.loads(DATA.read_text(encoding="utf-8"))
    files = outputs(data)
    stale = sorted(p for p in IMAGES.glob("*.svg") if p not in files) if IMAGES.is_dir() else []

    if args.check:
        differ = [p for p, content in files.items()
                  if not p.is_file() or p.read_text(encoding="utf-8") != content]
        problems = [f"differs from the data: {p.relative_to(ROOT)}" for p in differ]
        problems += [f"not generated by the data: {p.relative_to(ROOT)}" for p in stale]
        if problems:
            for problem in problems:
                print(f"progress: {problem}", file=sys.stderr)
            print("progress: run python3 tools/progress/render.py and commit the result", file=sys.stderr)
            return 1
        print(f"progress: all {len(files)} generated files match docs/progress/data.json")
        return 0

    IMAGES.mkdir(parents=True, exist_ok=True)
    written = 0
    for path, content in files.items():
        if not path.is_file() or path.read_text(encoding="utf-8") != content:
            with open(path, "w", encoding="utf-8", newline="\n") as handle:
                handle.write(content)
            written += 1
    for path in stale:
        path.unlink()
    print(f"progress: {written} of {len(files)} files written, {len(stale)} stale charts removed")
    return 0


if __name__ == "__main__":
    sys.exit(main())
